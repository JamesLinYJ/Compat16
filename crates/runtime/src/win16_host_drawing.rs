//! Typed drawing operations that cross from the Win16 ABI runtime to Windows.

use crate::{Win16HostDc, Win16HostDib, Win16HostGdiObject, Win16HostIcon};

/// A Win16 brush value accepted by APIs that allow COLOR_*+1 pseudo-brushes.
/// Ordinary GDI operations continue to require a mapped HGDIOBJ.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Win16HostBrush {
    Object(Win16HostGdiObject),
    SystemColor(u16),
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Win16DrawingPoint {
    pub x: i32,
    pub y: i32,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Win16DrawingRect {
    pub left: i32,
    pub top: i32,
    pub right: i32,
    pub bottom: i32,
}

