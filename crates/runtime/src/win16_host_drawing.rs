/// Native results are kept wider here; the Win16 runtime applies the export's
/// documented WORD or packed-WORD return convention.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum Win16DrawingResult {
    Void,
    Color(u32),
    Mode(i32),
    Point { x: i32, y: i32 },
    Bool(bool),
    Size { width: i32, height: i32 },
    Object(Option<Win16HostGdiObject>),
    RegionComplexity(i32),
    Rect { complexity: i32, rect: Win16DrawingRect },
    BoolPoint { success: bool, point: Win16DrawingPoint },
    BoolSize { success: bool, width: i32, height: i32 },
    Points { success: bool, points: Vec<Win16DrawingPoint> },
    SaveDc(i32),
    DrawText { height: i32, rect: Option<Win16DrawingRect> },
    /// Tabbed USER text APIs already return packed WORD width and height.
    PackedTextExtent(u32),
    Path {
        count: i32,
        points: Vec<Win16DrawingPoint>,
        point_types: Vec<u8>,
    },
    LineDda { success: bool, points: Vec<Win16DrawingPoint> },
    Dibits(i32),
}
