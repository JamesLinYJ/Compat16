#[test]
fn double_click_time_keeps_a_fitting_unsigned_word_and_drops_the_rest() {
    // 500 is the usual interval. 5000 is the published maximum. 32768 and
    // 65535 fit the Win16 UINT and must not be treated as signed overflow.
    // 65537 and the maximum host word do not fit; truncating them would
    // return 1 and 65535.
    for (host_value, guest) in [
        (0, 0),
        (500, 500),
        (5_000, 5_000),
        (32_768, 32_768),
        (65_535, 65_535),
        (65_536, 0),
        (65_537, 0),
        (0x1_0020, 0),
        (u32::MAX, 0),
    ] {
        let mut host = ClickHost {
            milliseconds: Ok(host_value),
        };
        assert_eq!(
            get_double_click_time(&mut host).unwrap(),
            guest,
            "{host_value}"
        );
    }
}

#[test]
fn double_click_time_reports_a_host_failure() {
    let mut host = ClickHost {
        milliseconds: Err("double-click time test failure"),
    };
    let error = get_double_click_time(&mut host).unwrap_err();
    assert_eq!(error.kind(), Kind::HostFailure);
}
