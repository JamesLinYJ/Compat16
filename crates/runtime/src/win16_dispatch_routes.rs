//! Exhaustive routing for decoded requests by their existing runtime service owner.

use win16_abi::Win16ApiRequest;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) enum DispatchRoute {
    Kernel,
    User,
    Gdi,
    Libraries,
}

pub(super) fn route_for_request(request: &Win16ApiRequest) -> DispatchRoute {
    match request {
        Win16ApiRequest::Kernel(_) => DispatchRoute::Kernel,
        Win16ApiRequest::User(_) | Win16ApiRequest::WindowEnumeration(_) => DispatchRoute::User,
        Win16ApiRequest::Libraries(_) => DispatchRoute::Libraries,
        Win16ApiRequest::GdiDrawing(_) => DispatchRoute::Gdi,
        Win16ApiRequest::GdiText(_) => DispatchRoute::Gdi,
        Win16ApiRequest::GdiObjects(_) => DispatchRoute::Gdi,
        Win16ApiRequest::InitTask { .. } => DispatchRoute::Kernel,
        Win16ApiRequest::KernelGlobalHeap(..) => DispatchRoute::Kernel,
        Win16ApiRequest::KernelMemory(..) => DispatchRoute::Kernel,
        Win16ApiRequest::KernelModule(..) => DispatchRoute::Kernel,
        Win16ApiRequest::KernelPathInfo(..) => DispatchRoute::Kernel,
        Win16ApiRequest::KernelFileSystem(..) => DispatchRoute::Kernel,
        Win16ApiRequest::KernelDiagnostics(..) => DispatchRoute::Kernel,
        Win16ApiRequest::KernelProfileSection(..) => DispatchRoute::Kernel,
        Win16ApiRequest::KernelString(..) => DispatchRoute::Kernel,
        Win16ApiRequest::KernelTask(..) => DispatchRoute::Kernel,
        Win16ApiRequest::System(..) => DispatchRoute::Kernel,
        Win16ApiRequest::Toolhelp(..) => DispatchRoute::Kernel,
        Win16ApiRequest::DestroyImage(..) => DispatchRoute::User,
        Win16ApiRequest::UserFamily(..) => DispatchRoute::User,
        Win16ApiRequest::UserScrollBar(..) => DispatchRoute::User,
        Win16ApiRequest::UserCursorAccelerator(..) => DispatchRoute::User,
        Win16ApiRequest::UserSystem(..) => DispatchRoute::User,
        Win16ApiRequest::UserUpdate(..) => DispatchRoute::User,
        Win16ApiRequest::WindowData(..) => DispatchRoute::User,
        Win16ApiRequest::ClassData(..) => DispatchRoute::User,
        Win16ApiRequest::NetworkRedirector(..) => DispatchRoute::User,
        Win16ApiRequest::WindowProperties(..) => DispatchRoute::User,
        Win16ApiRequest::GdiDevice(..) => DispatchRoute::Gdi,
        Win16ApiRequest::GdiServices(..) => DispatchRoute::Gdi,
        Win16ApiRequest::GdiSpool(..) => DispatchRoute::Gdi,
        Win16ApiRequest::GdiInternal(..) => DispatchRoute::Gdi,
        Win16ApiRequest::Commctrl(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Commdlg(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Ctl3d(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Dde(..) => DispatchRoute::Libraries,
        Win16ApiRequest::FpMath { .. } => DispatchRoute::Libraries,
        Win16ApiRequest::Keyboard(..) => DispatchRoute::Libraries,
        Win16ApiRequest::LzExpand(..) => DispatchRoute::Libraries,
        Win16ApiRequest::MediaIo(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Sound(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Mci(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Aux(..) => DispatchRoute::Libraries,
        Win16ApiRequest::MediaTime(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Joystick(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Mixer(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Midi(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Multimedia(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Ole2Disp(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Ole2DispConvert(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Ole2Nls(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Winnls(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Winmem32(..) => DispatchRoute::Libraries,
        Win16ApiRequest::PrintQueue(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Ole1(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Printer(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Driver(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Shell(..) => DispatchRoute::Libraries,
        Win16ApiRequest::ShellIcon(..) => DispatchRoute::Libraries,
        Win16ApiRequest::ShellExecution(..) => DispatchRoute::Libraries,
        Win16ApiRequest::ShellDrop(..) | Win16ApiRequest::ShellDrive(..) => DispatchRoute::Libraries,
        Win16ApiRequest::ShellRegistry(..) => DispatchRoute::Libraries,
        Win16ApiRequest::ToolhelpStack(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Ver(..) => DispatchRoute::Libraries,
        Win16ApiRequest::Winsock(..) => DispatchRoute::Libraries,
    }
}
