//! Checked IA-32 event delivery for architectural CPU contexts.
//!
//! Gate, descriptor, TSS and stack reads all pass through `CpuBus`; register
//! and hidden-cache changes are committed only after the complete new frame
//! has been prepared and written. Legacy selector projection remains owned by
//! its existing IVT/runtime path.

use guest_core::GuestMemory;

use crate::{Cpu, CpuCompatibilityGap, CpuError, CpuExecutionMode, SegmentResolver};

mod protected;
use protected::deliver_protected;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum EventSource {
    /// CD imm8 (including CD 03) is subject to the VM86 IOPL test.
    SoftwareInterrupt,
    /// The CC opcode checks gate DPL but not VM86 IOPL.
    SoftwareBreakpoint,
    /// F1 raises #DB as an instruction-generated trap, without a software
    /// interrupt gate privilege check or restart-on-delivery-fault rule.
    InstructionDebugTrap,
    /// INTO is software-generated and checks the gate DPL, but remains a trap
    /// whose saved IP is the following instruction and whose EXT bit is clear.
    SoftwareOverflow,
    Fault,
    Trap,
    ExternalInterrupt,
    /// Fault-class #DB generated by a DR0-DR3 instruction breakpoint.
    InstructionBreakpointFault,
    /// The machine's edge-triggered NMI ingress. It remains distinct from a
    /// maskable external request whose vector happens to be 2.
    NonMaskableInterrupt,
}

impl EventSource {
    pub(crate) const fn checks_software_interrupt_privilege(self) -> bool {
        matches!(
            self,
            Self::SoftwareInterrupt | Self::SoftwareBreakpoint | Self::SoftwareOverflow
        )
    }

    pub(crate) const fn checks_virtual_8086_iopl(self) -> bool {
        matches!(self, Self::SoftwareInterrupt)
    }

    const fn restarts_instruction_if_delivery_faults(self) -> bool {
        matches!(
            self,
            Self::SoftwareInterrupt | Self::SoftwareBreakpoint | Self::SoftwareOverflow
        )
    }

    /// EXT is clear for INT n, INT3, and INTO; it is set for external events,
    /// prior exceptions, and F1/#DB delivery.
    pub(crate) const fn sets_error_code_ext(self) -> bool {
        matches!(
            self,
            Self::Fault
                | Self::Trap
                | Self::InstructionDebugTrap
                | Self::InstructionBreakpointFault
                | Self::ExternalInterrupt
                | Self::NonMaskableInterrupt
        )
    }
}

impl CpuEvent {
    /// Build the flags image stored by an interrupt/exception frame. Faults
    /// request instruction restart with RF set. Software INT and F1/INT1 save
    /// RF clear; other trap/external sources retain the image except when an
    /// unfinished REP iteration explicitly requires RF in the saved frame.
    pub(crate) const fn saved_eflags(self, current: u32, intermediate_rep_boundary: bool) -> u32 {
        const EFLAGS_RF: u32 = 1 << 16;
        if intermediate_rep_boundary
            && matches!(
                self.source,
                EventSource::Trap
                    | EventSource::ExternalInterrupt
                    | EventSource::NonMaskableInterrupt
            )
        {
            return current | EFLAGS_RF;
        }
        match self.source {
            EventSource::Fault => current | EFLAGS_RF,
            EventSource::InstructionBreakpointFault => current,
            EventSource::SoftwareInterrupt
            | EventSource::SoftwareBreakpoint
            | EventSource::SoftwareOverflow
            | EventSource::InstructionDebugTrap => current & !EFLAGS_RF,
            _ => current,
        }
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) struct CpuEvent {
    pub(crate) vector: u8,
    pub(crate) source: EventSource,
    /// EIP placed in the frame if the event is accepted.
    pub(crate) saved_eip: u32,
    /// EIP used by a fault caused while validating this event's gate.
    pub(crate) instruction_ip: u32,
    /// Opcode that initiated instruction-generated delivery, when known.
    pub(crate) instruction_opcode: u8,
    /// `None` means this exception has no error-code slot; `Some(0)` is a
    /// real architecturally pushed zero error code.
    pub(crate) error_code: Option<u32>,
}

impl Cpu {
    /// Deliver an acknowledged external vector in the CPU's current mode.
    /// Callers must not route architectural Protected/VM86 interrupts through
    /// a real-mode IVT or a firmware service interception.
    pub fn deliver_external_interrupt(
        &mut self,
        vector: u8,
        memory: &mut impl GuestMemory,
        segments: &impl SegmentResolver,
    ) -> Result<(), CpuError> {
        let event = CpuEvent {
            vector,
            source: EventSource::ExternalInterrupt,
            saved_eip: self.regs.eip,
            instruction_ip: self.regs.eip,
            instruction_opcode: 0,
            error_code: None,
        };
        deliver_event_checked(self, event, None, memory, segments)
    }

    pub(crate) fn deliver_event(
        &mut self,
        event: CpuEvent,
        memory: &mut impl GuestMemory,
        segments: &impl SegmentResolver,
    ) -> Result<(), CpuError> {
        self.control_transfer = None;
        self.invalidate_control_transfer_provenance();
        if self.shutdown_reason.is_some() {
            return Err(self.shutdown_reason.as_ref().expect("checked").clone());
        }
        if !self.system.architectural_context_initialized {
            return Err(CpuError::CompatibilityGap {
                opcode: event.instruction_opcode,
                ip: event.instruction_ip,
                feature: CpuCompatibilityGap::ProtectedExceptionDelivery,
            });
        }
        self.normalize_model_eflags();
        match self.system.execution_mode(self.regs.eflags) {
            Some(CpuExecutionMode::RealAddress) => {
                self.enter_real_mode_interrupt_for_event(
                    event.vector,
                    event.source,
                    event.saved_eip,
                    event.instruction_ip,
                    event.instruction_opcode,
                    memory,
                )
            }
            Some(CpuExecutionMode::Protected | CpuExecutionMode::Virtual8086) => {
                let model = self.model;
                deliver_protected(self, event, memory, segments, model)
            }
            None => Err(CpuError::UnsupportedSystemMode {
                opcode: event.instruction_opcode,
                ip: event.instruction_ip,
            }),
        }
    }
}

pub(crate) fn deliver_event_checked<M: GuestMemory, S: SegmentResolver>(
    cpu: &mut Cpu,
    event: CpuEvent,
    original_error: Option<CpuError>,
    memory: &mut M,
    segments: &S,
) -> Result<(), CpuError> {
    match cpu.deliver_event(event, memory, segments) {
        Ok(()) => {
            cpu.intermediate_rep_boundary = false;
            if std::mem::replace(&mut cpu.pending_task_debug_trap, false) {
                cpu.system.debug.status |= 1 << 15;
                let task_debug = CpuEvent {
                    vector: 1,
                    source: EventSource::Trap,
                    saved_eip: cpu.regs.eip,
                    instruction_ip: cpu.regs.eip,
                    instruction_opcode: 0,
                    error_code: None,
                };
                return deliver_event_checked(cpu, task_debug, None, memory, segments);
            }
            Ok(())
        }
        Err(CpuError::TaskSwitchCommitted { target_ip, fault }) => {
            let fault_error = *fault;
            let Some(mut next_event) = exception_event(&fault_error, target_ip) else {
                return Err(CpuError::NestedExceptionDelivery {
                    original: Box::new(original_error.unwrap_or_else(|| fault_error.clone())),
                    delivery: Box::new(fault_error),
                });
            };
            next_event.saved_eip = target_ip;
            next_event.instruction_ip = target_ip;
            next_event.instruction_opcode = event.instruction_opcode;
            let causal = match original_error {
                Some(original) => CpuError::NestedExceptionDelivery {
                    original: Box::new(original),
                    delivery: Box::new(fault_error.clone()),
                },
                None => fault_error.clone(),
            };
            if causes_shutdown_after_double_fault(event, next_event) {
                return processor_shutdown(cpu, causal, fault_error.clone(), fault_error);
            }
            if needs_double_fault(event, next_event) {
                let double_fault = CpuEvent {
                    vector: 8,
                    source: EventSource::Fault,
                    saved_eip: target_ip,
                    instruction_ip: target_ip,
                    instruction_opcode: 0,
                    error_code: Some(0),
                };
                return deliver_fault_chain(cpu, double_fault, causal, memory, segments);
            }
            deliver_fault_chain(cpu, next_event, causal, memory, segments)
        }
        Err(delivery_error) => {
            let Some(mut next_event) = exception_event(&delivery_error, event.instruction_ip)
            else {
                return match original_error {
                    Some(original) => Err(CpuError::NestedExceptionDelivery {
                        original: Box::new(original),
                        delivery: Box::new(delivery_error),
                    }),
                    None => Err(delivery_error),
                };
            };
            if causes_shutdown_after_double_fault(event, next_event) {
                let cause = original_error.unwrap_or_else(|| delivery_error.clone());
                return processor_shutdown(cpu, cause, delivery_error.clone(), delivery_error);
            }
            let causal_error = match original_error {
                Some(original) if event.source == EventSource::Fault => {
                    CpuError::NestedExceptionDelivery {
                        original: Box::new(original),
                        delivery: Box::new(delivery_error.clone()),
                    }
                }
                _ => delivery_error.clone(),
            };
            if needs_double_fault(event, next_event) {
                let double_fault = CpuEvent {
                    vector: 8,
                    source: EventSource::Fault,
                    saved_eip: event.saved_eip,
                    instruction_ip: event.instruction_ip,
                    instruction_opcode: event.instruction_opcode,
                    error_code: Some(0),
                };
                return deliver_fault_chain(cpu, double_fault, causal_error, memory, segments);
            }
            next_event.saved_eip = if event.source.restarts_instruction_if_delivery_faults() {
                event.instruction_ip
            } else {
                event.saved_eip
            };
            next_event.instruction_ip = event.instruction_ip;
            next_event.instruction_opcode = event.instruction_opcode;
            deliver_fault_chain(cpu, next_event, causal_error, memory, segments)
        }
    }
}

fn deliver_fault_chain<M: GuestMemory, S: SegmentResolver>(
    cpu: &mut Cpu,
    event: CpuEvent,
    causal_error: CpuError,
    memory: &mut M,
    segments: &S,
) -> Result<(), CpuError> {
    match cpu.deliver_event(event, memory, segments) {
        Ok(()) => {
            cpu.intermediate_rep_boundary = false;
            if std::mem::replace(&mut cpu.pending_task_debug_trap, false) {
                cpu.system.debug.status |= 1 << 15;
                let task_debug = CpuEvent {
                    vector: 1,
                    source: EventSource::Trap,
                    saved_eip: cpu.regs.eip,
                    instruction_ip: cpu.regs.eip,
                    instruction_opcode: 0,
                    error_code: None,
                };
                return deliver_fault_chain(cpu, task_debug, causal_error, memory, segments);
            }
            Ok(())
        }
        Err(CpuError::TaskSwitchCommitted { target_ip, fault }) => {
            let Some(mut next_event) = exception_event(&fault, target_ip) else {
                return Err(CpuError::NestedExceptionDelivery {
                    original: Box::new(causal_error),
                    delivery: Box::new(*fault),
                });
            };
            next_event.saved_eip = target_ip;
            next_event.instruction_ip = target_ip;
            next_event.instruction_opcode = event.instruction_opcode;
            let combined = CpuError::NestedExceptionDelivery {
                original: Box::new(causal_error),
                delivery: Box::new(*fault.clone()),
            };
            if causes_shutdown_after_double_fault(event, next_event) {
                return processor_shutdown(cpu, combined, *fault.clone(), *fault);
            }
            if needs_double_fault(event, next_event) {
                let double_fault = CpuEvent {
                    vector: 8,
                    source: EventSource::Fault,
                    saved_eip: target_ip,
                    instruction_ip: target_ip,
                    instruction_opcode: 0,
                    error_code: Some(0),
                };
                return deliver_fault_chain(cpu, double_fault, combined, memory, segments);
            }
            deliver_fault_chain(cpu, next_event, combined, memory, segments)
        }
        Err(delivery_error) => {
            let next_fault = exception_event(&delivery_error, event.instruction_ip);
            let Some(mut next_event) = next_fault else {
                return Err(CpuError::NestedExceptionDelivery {
                    original: Box::new(causal_error),
                    delivery: Box::new(delivery_error),
                });
            };
            if causes_shutdown_after_double_fault(event, next_event) {
                return processor_shutdown(
                    cpu,
                    causal_error,
                    delivery_error.clone(),
                    delivery_error,
                );
            }
            next_event.saved_eip = event.saved_eip;
            next_event.instruction_ip = event.instruction_ip;
            next_event.instruction_opcode = event.instruction_opcode;
            let combined = CpuError::NestedExceptionDelivery {
                original: Box::new(causal_error),
                delivery: Box::new(delivery_error.clone()),
            };
            if needs_double_fault(event, next_event) {
                let double_fault = CpuEvent {
                    vector: 8,
                    source: EventSource::Fault,
                    saved_eip: event.saved_eip,
                    instruction_ip: event.instruction_ip,
                    instruction_opcode: event.instruction_opcode,
                    error_code: Some(0),
                };
                return deliver_fault_chain(cpu, double_fault, combined, memory, segments);
            }
            deliver_fault_chain(cpu, next_event, combined, memory, segments)
        }
    }
}

fn processor_shutdown(
    cpu: &mut Cpu,
    original: CpuError,
    delivery: CpuError,
    double_fault: CpuError,
) -> Result<(), CpuError> {
    let shutdown = CpuError::ProcessorShutdown {
        original: Box::new(original),
        delivery: Box::new(delivery),
        double_fault: Box::new(double_fault),
    };
    cpu.shutdown_reason = Some(shutdown.clone());
    cpu.halted = true;
    Err(shutdown)
}

pub(crate) fn exception_event(error: &CpuError, default_ip: u32) -> Option<CpuEvent> {
    let (vector, error_code, ip, source) = match error {
        CpuError::DivideError => (0, None, default_ip, EventSource::Fault),
        CpuError::DebugFault { ip } => (1, None, *ip, EventSource::Fault),
        CpuError::InstructionBreakpointFault { ip } => {
            (1, None, *ip, EventSource::InstructionBreakpointFault)
        }
        CpuError::BoundRangeFault { ip } => (5, None, *ip, EventSource::Fault),
        CpuError::InvalidOpcode { ip, .. } | CpuError::InvalidGroup { ip, .. } => {
            (6, None, *ip, EventSource::Fault)
        }
        CpuError::DeviceNotAvailableFault { ip } => (7, None, *ip, EventSource::Fault),
        CpuError::InvalidTssFault { error_code, ip } => {
            (10, Some(*error_code), *ip, EventSource::Fault)
        }
        CpuError::SegmentNotPresentFault { error_code, ip } => {
            (11, Some(*error_code), *ip, EventSource::Fault)
        }
        CpuError::StackSegmentFault { error_code, ip } => {
            (12, Some(*error_code), *ip, EventSource::Fault)
        }
        CpuError::GeneralProtectionFault { error_code, ip } => {
            (13, Some(*error_code), *ip, EventSource::Fault)
        }
        CpuError::PageFault { error_code, ip, .. } => {
            (14, Some(*error_code), *ip, EventSource::Fault)
        }
        CpuError::AlignmentCheckFault { error_code, ip } => {
            (17, Some(*error_code), *ip, EventSource::Fault)
        }
        // `ip` points just beyond the architectural 15-byte decode window
        // for diagnostics. The fault restarts at the instruction boundary.
        CpuError::InstructionTooLong { .. } => {
            (13, Some(0), default_ip, EventSource::Fault)
        }
        _ => return None,
    };
    Some(CpuEvent {
        vector,
        source,
        saved_eip: ip,
        instruction_ip: ip,
        instruction_opcode: 0,
        error_code,
    })
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum ExceptionClass {
    Benign,
    Contributory,
    PageFault,
    DoubleFault,
}

pub(crate) fn exception_class(vector: u8) -> ExceptionClass {
    match vector {
        8 => ExceptionClass::DoubleFault,
        14 => ExceptionClass::PageFault,
        0 | 10 | 11 | 12 | 13 => ExceptionClass::Contributory,
        _ => ExceptionClass::Benign,
    }
}

pub(crate) fn needs_double_fault(first: CpuEvent, second: CpuEvent) -> bool {
    use ExceptionClass::{Contributory, PageFault};
    let first_class = if first.source == EventSource::Fault {
        exception_class(first.vector)
    } else {
        ExceptionClass::Benign
    };
    matches!(
        (first_class, exception_class(second.vector)),
        (Contributory, Contributory) | (PageFault, Contributory | PageFault)
    )
}

fn causes_shutdown_after_double_fault(first: CpuEvent, second: CpuEvent) -> bool {
    first.source == EventSource::Fault
        && first.vector == 8
        && matches!(
            exception_class(second.vector),
            ExceptionClass::Contributory | ExceptionClass::PageFault
        )
}
