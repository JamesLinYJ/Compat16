//! IBM-compatible VGA BIOS mode metadata and register presets.
//!
//! Geometry and memory formats are checked against IBM's PS/2 VGA/XGA
//! Technical Reference, May 1992, Figure 2-4 and Figures 2-10 through 2-15.
//! A read-only legacy graphics reference provides the supported mode list; it
//! models a host framebuffer and does not provide the
//! guest VGA register programming implemented here. The register presets are
//! the standard BIOS parameter-table values used by VGA BIOS implementations;
//! IBM's manual is the authority for interpreting their register fields.

use super::{VGA_VRAM_BYTES, VgaState};

/// BIOS mode class used by the VGA memory and pixel helpers.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ModeKind {
    Text,
    Planar,
    Chain4,
    /// One-bit CGA-compatible packed mode 06h.
    Cga1,
    /// Two-bit CGA-compatible packed modes 04h and 05h.
    Cga2,
}

/// Geometry and BIOS page allocation for one standard VGA BIOS mode.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ModeInfo {
    pub mode: u8,
    /// Visible horizontal resolution in pixels.
    pub width: u16,
    /// Visible vertical resolution in pixels.
    pub height: u16,
    /// BIOS text-grid width. Graphics modes use the grid used by BIOS
    /// character and pixel services.
    pub columns: u16,
    /// BIOS text-grid height. Graphics modes use the grid used by BIOS
    /// character and pixel services.
    pub rows: u16,
    /// Character-cell scan lines used by the BIOS character services.
    pub char_height: u8,
    pub kind: ModeKind,
    /// BIOS display-page allocation stride, not the visible pixel byte count.
    /// Planar pixel helpers use a per-plane scanline stride derived from
    /// `width`; this value advances between BIOS pages.
    pub page_bytes: u32,
}

/// Information for a standard BIOS mode implemented by this device.
/// Unknown and extended modes return `None`.
pub fn mode_info(mode: u8) -> Option<ModeInfo> {
    let (width, height, columns, rows, char_height, kind, page_bytes) = match mode {
        0x00 | 0x01 => (360, 400, 40, 25, 16, ModeKind::Text, 0x0800),
        0x02 | 0x03 => (720, 400, 80, 25, 16, ModeKind::Text, 0x1000),
        // IBM's VGA BIOS default for monochrome mode is the 400-line 7+ form.
        0x07 => (720, 400, 80, 25, 16, ModeKind::Text, 0x1000),
        0x04 | 0x05 => (320, 200, 40, 25, 8, ModeKind::Cga2, 0x4000),
        0x06 => (640, 200, 80, 25, 8, ModeKind::Cga1, 0x4000),
        0x0d => (320, 200, 40, 25, 8, ModeKind::Planar, 0x2000),
        0x0e => (640, 200, 80, 25, 8, ModeKind::Planar, 0x4000),
        0x0f => (640, 350, 80, 25, 14, ModeKind::Planar, 0x8000),
        0x10 => (640, 350, 80, 25, 14, ModeKind::Planar, 0x8000),
        0x11 => (640, 480, 80, 30, 16, ModeKind::Planar, 0xa000),
        0x12 => (640, 480, 80, 30, 16, ModeKind::Planar, 0xa000),
        0x13 => (320, 200, 40, 25, 8, ModeKind::Chain4, 0x1_0000),
        _ => return None,
    };
    Some(ModeInfo {
        mode,
        width,
        height,
        columns,
        rows,
        char_height,
        kind,
        page_bytes,
    })
}

