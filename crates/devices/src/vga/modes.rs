fn registers_for(mode: u8) -> Option<&'static ModeRegisters> {
    match mode {
        0x00 | 0x01 => Some(&TEXT_40_COLOR),
        0x02 | 0x03 => Some(&TEXT_80_COLOR),
        0x07 => Some(&TEXT_80_MONO),
        0x04 | 0x05 => Some(&CGA_320_4_COLOR),
        0x06 => Some(&CGA_640_2_COLOR),
        0x0d => Some(&VGA_320_200_16),
        0x0e => Some(&VGA_640_200_16),
        0x0f => Some(&VGA_640_350_MONO),
        0x10 => Some(&VGA_640_350_16),
        0x11 => Some(&VGA_640_480_MONO),
        0x12 => Some(&VGA_640_480_16),
        0x13 => Some(&VGA_320_200_256),
        _ => None,
    }
}

fn bios_page_count(mode: u8) -> usize {
    match mode {
        0x00..=0x03 | 0x07 | 0x0d => 8,
        0x0e => 4,
        0x0f | 0x10 => 2,
        _ => 1,
    }
}

impl VgaState {
    /// Set a standard VGA BIOS mode. `clear` controls whether all BIOS pages
    /// for the selected memory model are initialized; false preserves VRAM.
    /// Unsupported modes and malformed VRAM leave the complete state intact.
    pub fn set_mode(&mut self, mode: u8, clear: bool) -> bool {
        let Some(info) = mode_info(mode) else {
            return false;
        };
        let Some(registers) = registers_for(mode) else {
            return false;
        };
        if self.vram.len() < VGA_VRAM_BYTES {
            return false;
        }

        self.sequencer = registers.sequencer;
        self.graphics = registers.graphics;
        self.crtc = registers.crtc;
        self.attribute = registers.attribute;
        self.misc_output = registers.misc_output;
        self.pel_mask = 0xff;
        super::palette::reset_dac_palette(&mut self.palette, mode);
        self.svga = None;
        self.bios_mode = mode;
        if clear {
            clear_mode_pages(
                &mut self.vram[..VGA_VRAM_BYTES],
                info,
                bios_page_count(mode),
            );
        }
        self.generation = self.generation.wrapping_add(1);
        true
    }
}

fn clear_mode_pages(vram: &mut [u8], info: ModeInfo, pages: usize) {
    match info.kind {
        ModeKind::Text => {
            let character_cells = (info.page_bytes as usize / 2) * pages;
            for cell in 0..character_cells {
                let base = cell * 4;
                vram[base] = b' ';
                vram[base + 1] = 0x07;
            }
        }
        ModeKind::Planar => {
            let plane_bytes = (info.page_bytes as usize * pages).min(64 * 1024);
            for address in 0..plane_bytes {
                let base = address * 4;
                vram[base..base + 4].fill(0);
            }
        }
        ModeKind::Chain4 => {
            vram[..info.page_bytes as usize].fill(0);
        }
        ModeKind::Cga1 => {
            // Mode 06h selects sequential CPU addressing and writes plane 0.
            for cpu_offset in 0..info.page_bytes as usize {
                vram[cpu_offset * 4] = 0;
            }
        }
        ModeKind::Cga2 => {
            for cpu_offset in 0..info.page_bytes as usize {
                let plane = cpu_offset & 1;
                let plane_address = cpu_offset >> 1;
                vram[plane_address * 4 + plane] = 0;
            }
        }
    }
}

